#!/usr/bin/env bash

if [[ -f "$ROOT_DIR/.env" ]]; then
  set -a
  # .env follows shell assignment syntax so the same values work in Compose and native mode.
  source "$ROOT_DIR/.env"
  set +a
fi

POSTGRES_DB="${POSTGRES_DB:-trades}"
POSTGRES_USER="${POSTGRES_USER:-trades}"
POSTGRES_PASSWORD="${POSTGRES_PASSWORD:-trades}"
POSTGRES_PORT="${POSTGRES_PORT:-5432}"
API_PORT="${API_PORT:-8080}"
UI_PORT="${UI_PORT:-4200}"
KAFKA_EXTERNAL_PORT="${KAFKA_EXTERNAL_PORT:-29092}"
KAFKA_BOOTSTRAP_SERVERS="${KAFKA_BOOTSTRAP_SERVERS:-localhost:9092}"
DATABASE_URL="${DATABASE_URL:-jdbc:postgresql://localhost:${POSTGRES_PORT}/${POSTGRES_DB}}"
DATABASE_USER="${DATABASE_USER:-$POSTGRES_USER}"
DATABASE_PASSWORD="${DATABASE_PASSWORD:-$POSTGRES_PASSWORD}"
UI_ORIGIN="${UI_ORIGIN:-http://localhost:${UI_PORT}}"
SERVER_PORT="$API_PORT"

export POSTGRES_DB POSTGRES_USER POSTGRES_PASSWORD POSTGRES_PORT
export API_PORT UI_PORT KAFKA_EXTERNAL_PORT KAFKA_BOOTSTRAP_SERVERS
export DATABASE_URL DATABASE_USER DATABASE_PASSWORD UI_ORIGIN SERVER_PORT
